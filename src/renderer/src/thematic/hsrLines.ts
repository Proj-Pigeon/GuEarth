export function hsrMileageAt(year: number): number {
  let value = 0
  for (const [seriesYear, km] of hsrGrowthSeries) {
    if (seriesYear <= year) value = km
  }
  return value
}

export function hsrLinesUpTo(year: number): HsrLine[] {
  return hsrLines.filter((line) => line.openedYear <= year)
}
